"""Validate an offline prepared bundle for the local PGlite rehearsal."""
import argparse
from pathlib import Path

from ingestion.prepare import InputError, digest, encode, parse_json
from ingestion.verification import validate_draft, table_columns


def validate_bundle(path):
    payload = validate_draft(parse_json(path.read_bytes()))
    rows = payload['rows']
    if len(rows.get('schemes', [])) != 1 or len(rows.get('scheme_versions', [])) != 1:
        raise InputError('One scheme and one version per import')
    if rows.get('ingestion_runs'):
        raise InputError('Import receipts are generated by the importer')
    if payload['unresolved_archive_conflicts'] != payload['original_record']['conflicts']:
        raise InputError('Archive conflicts were lost')
    if digest(encode(payload['original_record'])) != payload['verification']['input_record_sha256']:
        raise InputError('Original record binding mismatch')
    for row in rows.get('source_snapshots', []):
        source = next(s for s in rows['official_sources'] if s['id'] == row['source_id'])
        research = next((s for s in payload['verification']['sources']
                         if s['url'] == source['original_url'] and s.get('snapshot')), None)
        if (not research or research.get('reuse_status') != 'attribution_permitted'
                or any(research['snapshot'][k] != row[k] for k in ('content_sha256', 'fetched_at'))):
            raise InputError('Snapshot attribution mismatch')
        relative = Path(row['artifact_path'])
        artifact = (path.parent / relative).resolve()
        if relative.is_absolute() or not artifact.is_relative_to(path.parent.resolve()):
            raise InputError('Unsafe artifact path')
        if artifact.stat().st_size > 3_000_000 or digest(artifact.read_bytes()) != row['content_sha256']:
            raise InputError('Snapshot hash mismatch')
    if not rows.get('source_snapshots'):
        raise InputError('Captured source required')
    return {'payload': payload, 'columns': {t: sorted(c) for t, c in table_columns().items()}}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('draft', type=Path)
    args = parser.parse_args()
    print(encode(validate_bundle(args.draft)).decode('utf-8'))
